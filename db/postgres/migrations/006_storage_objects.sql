-- File storage (resumes, recordings, verifications, app-data, docs-ingest) for STORAGE_PROVIDER=mssql.
-- One row per object; (bucket, path) mirrors the object key used on the uploads volume.
CREATE TABLE IF NOT EXISTS public.storage_objects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT PK_storage_objects PRIMARY KEY,
    bucket        VARCHAR(100)  NOT NULL,
    path          VARCHAR(700)  NOT NULL,
    content       BYTEA NOT NULL,
    content_type  VARCHAR(200)  NULL,
    size_bytes    BIGINT         NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL CONSTRAINT DF_storage_objects_created_at DEFAULT (CURRENT_TIMESTAMP),
    updated_at    TIMESTAMPTZ NOT NULL CONSTRAINT DF_storage_objects_updated_at DEFAULT (CURRENT_TIMESTAMP)
  );
  CREATE UNIQUE INDEX IF NOT EXISTS UX_storage_objects_bucket_path
    ON public.storage_objects (bucket, path) INCLUDE (size_bytes, content_type, created_at, updated_at);
