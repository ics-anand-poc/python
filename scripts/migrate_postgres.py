"""Apply the ordered Supabase/PostgreSQL schema migrations."""

import hashlib
from pathlib import Path

from core.config import active_profile, postgres_settings

MIGRATIONS_DIR = Path(__file__).resolve().parents[1] / "db" / "postgres" / "migrations"


def main() -> None:
    if active_profile() != "vercel":
        raise RuntimeError("Set APP_PROFILE=vercel before applying PostgreSQL migrations")

    settings = postgres_settings()
    required = ("host", "database", "user", "password")
    missing = [key for key in required if not settings[key]]
    if missing:
        raise RuntimeError(f"Missing PostgreSQL connection properties: {', '.join(missing)}")

    import psycopg

    with psycopg.connect(
        host=settings["host"],
        port=settings["port"],
        dbname=settings["database"],
        user=settings["user"],
        password=settings["password"],
        sslmode=settings["sslmode"],
        connect_timeout=10,
    ) as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS public.__migrations (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    filename VARCHAR(260) NOT NULL UNIQUE,
                    checksum CHAR(64),
                    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            cursor.execute(
                "ALTER TABLE public.__migrations ADD COLUMN IF NOT EXISTS checksum CHAR(64)"
            )
        connection.commit()

        for path in sorted(MIGRATIONS_DIR.glob("*.sql")):
            sql = path.read_text(encoding="utf-8-sig")
            checksum = hashlib.sha256(sql.replace("\r\n", "\n").encode("utf-8")).hexdigest()
            with connection.cursor() as cursor:
                cursor.execute(
                    "SELECT checksum FROM public.__migrations WHERE filename = %s",
                    (path.name,),
                )
                row = cursor.fetchone()
                if row:
                    stored = row[0].strip() if row[0] else None
                    if stored and stored != checksum:
                        raise RuntimeError(
                            f"Migration {path.name} changed after being applied; add a new migration instead"
                        )
                    if not stored:
                        cursor.execute(
                            "UPDATE public.__migrations SET checksum = %s WHERE filename = %s",
                            (checksum, path.name),
                        )
                        connection.commit()
                    print(f"[done] {path.name}")
                    continue

                try:
                    cursor.execute(sql)
                    cursor.execute(
                        "INSERT INTO public.__migrations (filename, checksum) VALUES (%s, %s)",
                        (path.name, checksum),
                    )
                    connection.commit()
                except Exception:
                    connection.rollback()
                    raise
            print(f"[applied] {path.name}")


if __name__ == "__main__":
    main()
